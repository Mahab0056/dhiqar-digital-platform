import { chromium } from 'playwright'
const base = 'http://localhost:8787', phone = '07801112233'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const ctx = await browser.newContext({ locale: 'ar-IQ' })
const otp = await (await ctx.request.post(`${base}/api/onboarding/request-otp`, { data: { phone } })).json()
await ctx.request.post(`${base}/api/onboarding/verify-phone`, { data: { phone, challengeId: otp.challengeId, otp: '246810' } })
const page = await ctx.newPage()
await page.setViewportSize({ width: 390, height: 844 })
await page.goto(`${base}/citizen`, { waitUntil: 'networkidle' })
await page.waitForTimeout(600)
const h = await page.evaluate(() => document.documentElement.scrollHeight)
for (let y = 0; y < h; y += 400) { await page.evaluate(y => scrollTo(0, y), y); await page.waitForTimeout(120) }
await page.evaluate(() => scrollTo(0, document.documentElement.scrollHeight))
await page.waitForTimeout(500)
await page.screenshot({ path: 'qa-screens/audit-citizen-mobile-bottom-nav-overlap.png' })
await page.goto(`${base}/service/online-appointment`, { waitUntil: 'networkidle' })
await page.waitForTimeout(500)
await page.locator('.gov-doc-slots').scrollIntoViewIfNeeded()
await page.waitForTimeout(400)
await page.screenshot({ path: 'qa-screens/audit-citizen-appointment-fake-documents.png' })
await page.setViewportSize({ width: 1366, height: 768 })
await page.goto(`${base}/citizen/pay/PAY-2026-00001`, { waitUntil: 'networkidle' })
await page.waitForTimeout(400)
// create a new pending payment? the first one is paid; use dashboard to find another - skip if paid
await page.goto(`${base}/citizen/application/TQD-2026-0003`, { waitUntil: 'networkidle' })
await page.waitForTimeout(600)
await page.screenshot({ path: 'qa-screens/audit-citizen-application-header-invisible.png' })
await page.goto(`${base}/citizen`, { waitUntil: 'networkidle' })
await page.waitForTimeout(600)
await page.screenshot({ path: 'qa-screens/audit-citizen-identity-card-invisible.png' })
await page.goto(`${base}/citizen/feedback/TQD-CMP-2026-00001`, { waitUntil: 'networkidle' })
await page.waitForTimeout(600)
await page.screenshot({ path: 'qa-screens/audit-citizen-feedback-detail-header-invisible.png' })
